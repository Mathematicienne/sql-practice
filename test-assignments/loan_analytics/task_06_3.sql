-- ============================================
-- Задача: Вывести займы, у которых сумма выдачи выше среднего среди других займов.
-- Источник: Тестовое задание по займам
-- Тема: Подзапросы, сравнение со средним значением
-- ============================================

SELECT 
    loan_id,
    loan_amount
FROM view_loans
WHERE loan_amount > (
    SELECT AVG(loan_amount)
    FROM view_loans
)

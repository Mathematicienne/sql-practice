-- ============================================
-- Задача: Выведите список регионов, откуда клиенты с датой регистрации после 1 января 2023 года.
-- Источник: Тестовое задание по займам
-- Тема: JOIN, фильтрация по дате
-- ============================================

SELECT
    DISTINCT
    c.region_id,
    r.timezone
FROM customers c
LEFT JOIN regions r
    ON c.region_id = r.region_id
WHERE c.created > '2023-01-01'
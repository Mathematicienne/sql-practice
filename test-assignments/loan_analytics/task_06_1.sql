-- ============================================
-- Задача: Пронумеровать займы по клиенту по дате выдачи по повторным займам 
-- (в выборку должны попадать только повторные выдачи). 
-- Вывести поля: client_id, loan_id, номер повторного займа. 
-- Сортировка: по клиенту и по номеру повторного займа от максимального к минимальному.
-- Источник: Тестовое задание по займам
-- Тема: Нумерация строк в группе для повторных займов
-- ============================================

SELECT
    client_id,
    loan_id,
    ROW_NUMBER() OVER(
        PARTITION BY client_id
        ORDER BY created_at
    ) AS number_repeat_loan
FROM view_loans
WHERE client_type = 'Repeated'
ORDER BY 
    client_id, 
    number_repeat_loan DESC
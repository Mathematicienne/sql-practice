-- ============================================
-- Задача: Найдите имена клиентов, которые либо:
-- были порекомендованы любым клиентом с id != 2.
-- не были порекомендованы ни одним клиентом.
-- Источник: leetcode.com/problemset/database/, задача №584
-- Тема: Фильтрация с учётом NULL (OR IS NULL)
-- ============================================

SELECT name
FROM Customer
WHERE referee_id != 2
    OR referee_id IS NULL
-- ============================================
-- Задача: Найдите производителей, выпускающих по меньшей мере три различных модели ПК. Вывести: Maker, число моделей ПК.
-- Источник: sql-ex.ru/learn_exercises.php, задача №20
-- Тема: Агрегация и фильтрация групп (GROUP BY, HAVING)
-- ============================================

SELECT 
    Maker, 
    COUNT(*) AS count
FROM Product
WHERE type = 'PC'
GROUP BY Maker
HAVING count(*) >= 3
